def build_features(d):
    X = pd.DataFrame(index=d.index)
    X["log_params"] = d["log_params"]
    X["years_since_2023"] = d["years_since_2023"].fillna(d["years_since_2023"].median())
    X["generation"] = d["generation"].fillna(0).clip(0, 5)
    for col in ["has_chat_template", "is_official", "is_moe", "is_adapter", "is_merged"]:
        X[col] = d[col].astype(int)
    X = X.join(pd.get_dummies(d["model_type"], prefix="type").astype(int))
    X = X.join(pd.get_dummies(d["family_group"], prefix="family").astype(int))
    X = X.join(pd.get_dummies(d["precision_group"], prefix="precision").astype(int))
    return X


