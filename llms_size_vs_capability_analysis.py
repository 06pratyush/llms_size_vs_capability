def binned_median(x, y, n_bins=22, min_count=12):
    edges = np.logspace(np.log10(x.min()), np.log10(x.max()) + 1e-9, n_bins + 1)
    which = np.digitize(x, edges) - 1
    centers, medians = [], []
    for i in range(n_bins):
        mask = which == i
        if mask.sum() >= min_count:
            centers.append(np.sqrt(edges[i] * edges[i + 1]))
            medians.append(np.median(y[mask]))
    return np.array(centers), np.array(medians)


