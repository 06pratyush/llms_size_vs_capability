# ---- The size-only prediction (used by almost every part) ---------------------------
# Fit a straight line: score = start + slope × log10(size).
# log10 means "how many times ×10": 1B -> 0, 10B -> 1, 100B -> 2.
# So the slope is "points gained every time the model gets 10 times bigger".
size_line = LinearRegression().fit(df[["log_params"]], df["avg_score"])
SLOPE = float(size_line.coef_[0])
INTERCEPT = float(size_line.intercept_)
R2_SIZE = float(size_line.score(df[["log_params"]], df["avg_score"]))
df["expected_score"] = size_line.predict(df[["log_params"]])
