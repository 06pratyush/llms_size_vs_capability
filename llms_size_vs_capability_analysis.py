def frontier_of(d):
    d = d.sort_values(["footprint_4bit_gb", "avg_score"], ascending=[True, False])
    best, rows = -np.inf, []
    for idx, row in d.iterrows():
        if row["avg_score"] > best:
            best = row["avg_score"]
            rows.append(idx)
    return d.loc[rows]


