def strip_html(value):
    return re.sub(r"<[^>]+>", "", value).strip() if isinstance(value, str) else value


def to_bool(series):
    if series.dtype == bool:
        return series
    return series.astype(str).str.strip().str.lower().isin(["true", "1", "yes", "y", "t"])


def short_type(raw):
    text = str(raw).lower()
    if "merge" in text:
        return "Merge"
    if "fine-tuned" in text or "fine tuned" in text:
        return "Fine-tuned"
    if "chat" in text:
        return "Chat-tuned"
    if "continuously" in text:
        return "Other"            # continued pretraining: too few models to stand alone
    if "pretrained" in text:
        return "Pretrained (base)"
    return "Other"


