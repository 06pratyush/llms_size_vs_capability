def family_of(architecture):
    text = str(architecture).strip()
    if text.lower() in ("", "?", "unknown", "nan", "none"):
        return "Unknown"
    for key, name in FAMILY_RULES:
        if key in text.lower():
            return name
    match = re.match(r"([A-Za-z0-9]+?)(For|Model|LMHead)", text)
    return match.group(1) if match else text


